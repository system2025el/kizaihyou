-- ============================================================================
-- 05: 機材表ヘッダから「現在の申請の操作履歴」を直接指す
--   機材表承認画面は現在の内容ではなく申請時点のスナップショットを表示する。
--   申請後も申請者がメモとして編集できる仕様のため、現在の内容を見せると
--   承認した内容と申請された内容が食い違うため。
--
--   どの履歴が申請かはact_namの文字列（'申請（受注部担当者：◯◯）'）でも
--   判定できるが、文言を変えた瞬間に壊れるのでヘッダから参照を張る。
--   差戻し後に再申請されたら最新の申請を指すように更新する。
-- ============================================================================
alter table public.t_kizaihyou
  add column shinsei_his_id bigint references public.t_kizaihyou_his (his_id) on delete set null;

comment on column public.t_kizaihyou.shinsei_his_id is
  '現在の申請にあたる操作履歴。承認画面はこの履歴のsnapshotを表示する';
